#!/usr/bin/env python3
"""Derive public sentinel constants and their exact polynomial correction.

Clean author /root, logical workspace 01a1be54-c6e9-73d3-8a85-5e6f9a76a492.
Only local independently generated Boolean witness data is read.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
record = json.loads((HERE / "guard-witness.json").read_text())
pairs = [(int(a, 16), int(b, 16)) for a, b in record["public_pairs_hex"]]
assert len(pairs) == 14
correction = 0
for a, b in pairs:
    product = 0
    for i in range(128):
        if b >> i & 1:
            product ^= a << i
    correction ^= product
lines = ["// Public fixed sentinels; generated by guard_generate.py.",
         "// Polynomial bit i is coefficient x^i; no field reduction here.",
         "pub(super) const PAIRS: [(u128, u128); 14] = ["]
lines += [f"    (0x{a:032x}, 0x{b:032x})," for a, b in pairs]
lines += ["];", "pub(super) const CORRECTION: [u128; 2] = [",
          f"    0x{correction & ((1 << 128)-1):032x},",
          f"    0x{correction >> 128:032x},", "];", ""]
(HERE / "guard_constants.rs").write_text("\n".join(lines))
print(json.dumps({"public_pairs": len(pairs), "correction_hex": f"{correction:064x}"}))
