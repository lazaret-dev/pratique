#!/usr/bin/env python3
"""Generate a Boolean Karatsuba circuit from polynomial identities.

Independent experiment, Codex session 01a1be54-c6e9-73d3-8a85-5e6f9a76a492,
2026-11-08 America/Chicago. Inputs contain 64 independent bit-sliced lanes.
This generator is development tooling; the generated Rust needs no dependency.
"""

from pathlib import Path


def generate():
    statements = []
    serial = 0
    counts = {"xor": 0, "and": 0}

    def expression(left, op, right):
        nonlocal serial
        if left == "0":
            return right if op == "^" else "0"
        if right == "0":
            return left if op == "^" else "0"
        name = f"v{serial}"
        serial += 1
        counts["xor" if op == "^" else "and"] += 1
        statements.append(f"    let {name} = {left} {op} {right};")
        return name

    def product(a, b):
        size = len(a)
        if size == 1:
            return [expression(a[0], "&", b[0])]
        half = size // 2
        # A=A0+x^half A1; B=B0+x^half B1. Addition is XOR.
        low = product(a[:half], b[:half])
        high = product(a[half:], b[half:])
        ax = [expression(x, "^", y) for x, y in zip(a[:half], a[half:])]
        bx = [expression(x, "^", y) for x, y in zip(b[:half], b[half:])]
        middle = product(ax, bx)
        cross = [expression(expression(m, "^", l), "^", h)
                 for m, l, h in zip(middle, low, high)]
        out = ["0"] * (size + size - 1)
        for offset, part in [(0, low), (half, cross), (size, high)]:
            for index, value in enumerate(part, offset):
                out[index] = expression(out[index], "^", value)
        return out

    output = product([f"a[{i}]" for i in range(64)],
                     [f"b[{i}]" for i in range(64)])
    lines = [
        "// Generated by generate.py from the documented polynomial identity.",
        f"// Circuit: {counts['and']} AND and {counts['xor']} XOR operations.",
        "#[inline(never)]",
        "pub(super) fn planes_product<T>(a: &[T; 64], b: &[T; 64]) -> [T; 128]",
        "where T: Copy + Default + core::ops::BitXor<Output = T> + core::ops::BitAnd<Output = T> {",
        *statements,
        "    [" + ", ".join(output + ["T::default()"]) + "]",
        "}",
        "",
    ]
    Path(__file__).with_name("circuit.rs").write_text("\n".join(lines))
    print(counts)


if __name__ == "__main__":
    generate()
